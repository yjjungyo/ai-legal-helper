def prepare():
    """증거·질의·정답·해시를 저장하여 시험 전 정답 기준을 동결한다.

    Returns:
        생성된 골드셋 경로.
    Raises:
        FileExistsError: 이미 동결된 정답을 실수로 덮어쓰려는 경우.
    """
    DEST.mkdir(parents=True, exist_ok=True)
    target = DEST / 'gold_v1.json'
    if target.exists():
        raise FileExistsError('동결된 Gold는 덮어쓰지 않습니다.')
    for case in CASES:
        case_dir = ROOT / 'docs/testset' / case['id']
        (case_dir / 'evidence').mkdir(parents=True, exist_ok=True)
        case['gold_facts'] = [{'id': f"{case['id']}-F{i:02}", 'statement': text, 'evidence': f'E{(i-1)//4+1:02}', 'essential': True} for i, text in enumerate(case.pop('facts'), 1)]
        case['gold_issues'] = [{'id': f"{case['id']}-I{i:02}", 'statement': text} for i, text in enumerate(case.pop('issues'), 1)]
        # 제품에는 정답 ID나 법률 결론을 주지 않고 원자료의 사실 진술만 제공한다.
        for number in range(1, 4):
            facts = [f['statement'] for f in case['gold_facts'] if f['evidence'] == f'E{number:02}']
            (case_dir / 'evidence' / f'E{number:02}_synthetic_record.txt').write_text('합성 테스트 자료 (실존 인물·사건 아님)\n' + '\n'.join(facts), encoding='utf-8')
        (case_dir / 'question.txt').write_text(case['question'], encoding='utf-8')
        (case_dir / 'gold_answer_private.md').write_text('# 평가자 전용 정답\n\n' + case['answer'] + '\n\n금지 판단: ' + '; '.join(case['forbidden']) + '\n\n공식 출처:\n' + '\n'.join(SOURCES[k]['url'] for k in case['sources']), encoding='utf-8')
    payload = {'version': 'KPI5-GOLD-v1.0', 'frozen_before_run': True, 'date_kst': '2026-11-15', 'review_status': 'PROVISIONAL_AI_AUTHORED_OFFICIAL_SOURCE_CHECKED', 'sources': SOURCES, 'cases': CASES,
               'rules': {'fact_precision': '원자화·의미 중복 제거 후 Gold에 의해 지지되는 추출 사실 수/전체 추출 사실 수. 복합 진술은 전 요소 충족 필요. 자료의 주장 여부를 보존해야 함.', 'fact_recall': '추출 결과로 완전히 재현된 필수 Gold 사실 수/전체 필수 Gold 사실 수', 'issue_recall': '실제 Planner에서 식별된 필수 쟁점 수/전체 필수 쟁점 수. 답변 내 쟁점 커버리지는 별도 보조지표.', 'legal_accuracy': '실제 답변의 법령·판례 인용-주장 단위 중 존재·내용·관련성·시점·적용타당성 5개 항목 모두 충족한 수/전체 인용-주장 수. 확인 불가는 보수적으로 미충족.', 'empty_denominator': 'N/A, PASS 금지', 'thresholds': {'fact_precision': .90, 'fact_recall': .90, 'issue_recall': .90, 'legal_accuracy': .95}}}
    text = json.dumps(payload, ensure_ascii=False, indent=2)
    target.write_text(text, encoding='utf-8')
    # Windows의 개행 변환까지 반영한 실제 저장 바이트를 해시하여 실행 환경에 독립적으로 검증한다.
    (DEST / 'gold_v1.sha256').write_text(hashlib.sha256(target.read_bytes()).hexdigest(), encoding='ascii')
    (DEST / 'README.md').write_text('# KPI 측정 신규 합성 사례 5건\n\nSC-021~025, 사건당 증거 3개·질의 1개·필수 사실 12개. 총 필수 사실 60개, 필수 쟁점 23개.\n\n평가자 전용 정답은 제품 입력에서 제외한다. 법령 적용 기준은 각 사건 행위 시점이며 공식 출처를 연결했다. Gold는 전문가 확정 전 잠정안이다. 채점은 실제 DB 추출 사실·Planner 반환값·최종 사용자 답변을 구분한다.\n\nLLM Judge 의미매칭에 따른 자동 실측은 전문가 검증을 대체하지 않는다. 추출·상담의 제품 비용과 심사 비용은 분리하고 Langfuse 원본을 보존한다.\n', encoding='utf-8')
    return target


def export_frozen_case_metadata():
    """동결된 전체 정답을 사건별 폴더에 복사하고 파일 안내를 작성한다.

    Returns:
        사건별 정답 JSON 경로 목록. 원본 Gold와 해시는 변경하지 않는다.
    """
    gold = json.loads((DEST / 'gold_v1.json').read_text(encoding='utf-8'))
    parent_hash = (DEST / 'gold_v1.sha256').read_text().strip()
    paths = []
    for case in gold['cases']:
        folder = ROOT / 'docs/testset' / case['id']
        payload = {'gold_version': gold['version'], 'parent_gold_sha256': parent_hash,
                   'review_status': gold['review_status'], 'case': case,
                   'scoring_rules': gold['rules'], 'official_sources': {k: gold['sources'][k] for k in case['sources']}}
        path = folder / 'gold.json'
        path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding='utf-8')
        (folder / 'README.md').write_text(
            '# ' + case['id'] + ' ' + case['title'] + '\n\n'
            '- `evidence/`: 제품에 등록할 합성 증거 TXT 3개\n'
            '- `question.txt`: 제품에 전달할 상담 질의\n'
            '- `gold.json`: 필수 사실 12개, 필수 쟁점 ' + str(len(case['gold_issues'])) + '개, 정답, 금지 판단, 측정식·공식 출처\n'
            '- `gold_answer_private.md`: 평가자용 정답 해설\n\n'
            '정답 파일은 제품에 주입하지 않는다. 원본 동결 Gold와 해시는 `../KPI5_20261115/`에 보존한다. '
            'Gold는 공식 출처를 대조한 AI 작성 잠정안이며 전문가 확정 전이다. 이번 보고 대상은 SC-021 한 건이다.\n', encoding='utf-8')
        paths.append(path)
    return paths


