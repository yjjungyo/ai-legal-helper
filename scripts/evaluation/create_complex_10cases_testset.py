def main():
    print(f"Generating 10 complex test cases under {BASE_DIR}...")
    for tc in TEST_CASES:
        case_dir_name = f"{tc['case_id']}_{tc['title']}"
        case_dir = os.path.join(BASE_DIR, case_dir_name)
        os.makedirs(case_dir, exist_ok=True)

        # 1. 질문_단계별.txt 작성
        q_lines = [
            f"사건번호: {tc['case_id']}",
            f"사건명: {tc['title']}",
            f"분류: {tc['category']}",
            f"보증금: {tc['deposit']:,}원",
            "동일 사건, 동일 대화 흐름에서 단계별 증거를 추가 등록하며 질의를 반복 수행한다.",
            ""
        ]
        for t in tc["turns"]:
            q_lines.append(f"[{t['step']}차] 신규증거: {', '.join(t['new_evidence'])}")
            q_lines.append(f"평가초점: {t['focus']}")
            q_lines.append(f"질문: {t['question']}")
            q_lines.append("")

        with open(os.path.join(case_dir, "질문_단계별.txt"), "w", encoding="utf-8") as f:
            f.write("\n".join(q_lines))

        # 2. 평가정답_비공개.txt 작성
        ans_lines = [
            f"[{tc['case_id']} 법률 정답 및 평가 루브릭]",
            ""
        ]
        for t in tc["turns"]:
            ans_lines.append(f"=== {t['step']}차 정답 및 판정기준 ===")
            ans_lines.append(f"기대답변: {t['expected']}")
            ans_lines.append(f"핵심판정: {t['check_items']}")
            ans_lines.append("")

        with open(os.path.join(case_dir, "평가정답_비공개.txt"), "w", encoding="utf-8") as f:
            f.write("\n".join(ans_lines))

        # 3. 증거 폴더 및 파일 작성
        evidence_root = os.path.join(case_dir, "증거")
        os.makedirs(evidence_root, exist_ok=True)
        for stage, files in tc["evidence_files"].items():
            stage_dir = os.path.join(evidence_root, stage)
            os.makedirs(stage_dir, exist_ok=True)
            for fname, content in files.items():
                fpath = os.path.join(stage_dir, fname)
                with open(fpath, "w", encoding="utf-8") as f:
                    f.write(content.strip() + "\n")

        print(f"  [+] Created {tc['case_id']}: {case_dir_name} ({len(tc['turns'])} turns, {sum(len(f) for f in tc['evidence_files'].values())} evidence files)")

    print("All 10 complex test cases generated successfully!")

if __name__ == "__main__":
    main()
